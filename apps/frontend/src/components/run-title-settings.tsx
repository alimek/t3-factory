/** Row controls are narrower and lower than the composer's select fields. */
const rowChoiceClass = "h-8 w-55";

const errorMessage = (cause: unknown, fallback: string) =>
  cause instanceof ApiError
    ? [cause.message, ...cause.detail.issues.map((issue) => issue.message)].join(" ")
    : cause instanceof Error
      ? cause.message
      : fallback;

/** A saved choice the live catalog no longer offers stays visible, disabled, with its id. */
function withSaved(choices: readonly MenuChoice[], value: string, noun: string) {
  if (!value || choices.some((choice) => choice.id === value)) return choices;
  return [
    {
      id: value,
      label: `Saved ${noun} (unavailable): ${value}`,
      disabled: true,
    },
    ...choices,
  ];
}

/**
 * Settings → Run titles: the installation-wide Generate Run titles setting. The host changes it,
 * each change saved at once; an approved client sees the same fields read-only.
 */
export function RunTitleSettings() {
  const host = useClientScope() === "host";
  const [setting, setSetting] = useState<RunTitleSetting | null>(null);
  const [capabilities, setCapabilities] = useState<AgentCapabilities | null>(null);
  const [loadError, setLoadError] = useState("");
  const [loads, setLoads] = useState(0);
  const [saving, setSaving] = useState(false);
  const [saveError, setSaveError] = useState("");
  useEffect(() => {
    let active = true;
    setLoadError("");
    // The setting is not delivered live, so the section reads it whenever it opens.
    api.getRunTitleSetting().then(
      (value) => active && setSetting(value),
      (cause: unknown) =>
        active && setLoadError(errorMessage(cause, "Factory could not read Run titles.")),
    );
    api.getAgentCapabilities().then(
      (value) => active && setCapabilities(value),
      () => active && setCapabilities(null),
    );
    return () => {
      active = false;
    };
  }, [loads]);
  const save = async (next: UpdateRunTitleSettingInput) => {
    setSaving(true);
    setSaveError("");
    try {
      setSetting(await api.updateRunTitleSetting(next));
    } catch (cause) {
      setSaveError(errorMessage(cause, "Factory could not save Run titles."));
    } finally {
      setSaving(false);
    }
  };
  return (
    <SettingsPage
      title="Run titles"
      description="Give each new Run a short title generated by a T3 model. A Run you rename keeps your title."
      hostManaged={!host}
    >
      {loadError && (
        <Alert variant="destructive">
          <AlertDescription className="flex flex-wrap items-center justify-between gap-2">
            {loadError}
            <Button
              type="button"
              variant="outline"
              size="sm"
              onClick={() => setLoads((n) => n + 1)}
            >
              Retry
            </Button>
          </AlertDescription>
        </Alert>
      )}
      {saveError && (
        <Alert variant="destructive">
          <AlertDescription>{saveError}</AlertDescription>
        </Alert>
      )}
      {setting ? (
        <MutationGate>
          <RunTitleFields
            setting={setting}
            capabilities={capabilities}
            editable={host && !saving}
            onSave={(next) => void save(next)}
          />
        </MutationGate>
      ) : (
        !loadError && (
          <p role="status" className="text-sm text-muted-foreground">
            Reading Run titles…
          </p>
        )
      )}
      {setting?.diagnostic && <LatestResult diagnostic={setting.diagnostic} />}
      <HowItWorks />
    </SettingsPage>
  );
}

/** The provider instances T3 offers; one whose harness cannot report stays visible, disabled. */
function providerChoices(providers: readonly AgentProviderCapability[]): MenuChoice[] {
  return providers.map((entry) => ({
    id: entry.providerInstanceId,
    label: entry.displayName ?? entry.providerInstanceId,
    ...(entry.reporting.supported
      ? {}
      : {
          badge: "No Factory reporting yet",
          description: entry.reporting.explanation,
          disabled: true,
        }),
  }));
}

function settingState({ enabled, model }: RunTitleSetting) {
  if (enabled && model) return "On · applies to Runs started from now on.";
  return model
    ? "Off · new Runs use the first line of their prompt as the title."
    : "Off · choose a provider instance and model to turn it on.";
}

function RunTitleFields({
  setting,
  capabilities,
  editable,
  onSave,
}: {
  setting: RunTitleSetting;
  capabilities: AgentCapabilities | null;
  editable: boolean;
  onSave: (next: UpdateRunTitleSettingInput) => void;
}) {
  const { enabled, model } = setting;
  return (
    <SettingsGroup label="Generation">
      <SettingsRow
        title="Generate Run titles"
        description={settingState(setting)}
        control={(text) => (
          <Switch
            aria-labelledby={text.title}
            aria-describedby={text.description}
            checked={enabled}
            disabled={!editable || (!enabled && !model)}
            onCheckedChange={(checked) => onSave({ enabled: checked, model })}
          />
        )}
      />
      <ModelRows
        model={model}
        capabilities={capabilities}
        editable={editable}
        onSave={(next) => onSave({ enabled, model: next })}
      />
    </SettingsGroup>
  );
}

/** Provider instance, model and options from the live T3 catalog. */
function ModelRows({
  model,
  capabilities,
  editable,
  onSave,
}: {
  model: RunTitleModel | null;
  capabilities: AgentCapabilities | null;
  editable: boolean;
  onSave: (next: RunTitleModel) => void;
}) {
  const providers = capabilities?.state === "ready" ? capabilities.providers : [];
  const provider = providers.find(
    (entry) => entry.providerInstanceId === model?.providerInstanceId,
  );
  const offered = provider?.models.find((entry) => entry.id === model?.modelId);
  return (
    <>
      <ProviderRow
        model={model}
        providers={providers}
        unavailable={
          capabilities?.state === "ready"
            ? undefined
            : (capabilities?.explanation ?? "Connect to T3 to load provider instances and models.")
        }
        editable={editable}
        onSave={onSave}
      />
      <ModelRow model={model} provider={provider} editable={editable} onSave={onSave} />
      {model &&
        offered?.options?.map((descriptor) => (
          <OptionRow
            key={descriptor.id}
            descriptor={descriptor}
            model={model}
            editable={editable}
            onSave={onSave}
          />
        ))}
    </>
  );
}

/** Choosing a provider instance takes its first model. */
function ProviderRow({
  model,
  providers,
  unavailable,
  editable,
  onSave,
}: {
  model: RunTitleModel | null;
  providers: readonly AgentProviderCapability[];
  /** Why the catalog is not available, when it is not. */
  unavailable: string | undefined;
  editable: boolean;
  onSave: (next: RunTitleModel) => void;
}) {
  const choose = (id: string) => {
    const first = providers.find((entry) => entry.providerInstanceId === id)?.models[0];
    if (first)
      onSave({
        providerInstanceId: id,
        modelId: first.id,
        modelOptions: buildOptions(first.options, []),
      });
  };
  const value = model?.providerInstanceId ?? "";
  return (
    <SettingsRow
      title="Provider instance"
      description={unavailable}
      control={
        <ChoiceMenu
          id="run-title-provider"
          label="Provider instance"
          value={value}
          choices={withSaved(providerChoices(providers), value, "provider")}
          onChange={choose}
          disabled={!editable || !providers.length}
          placeholder={providers.length ? "Choose a provider instance" : "Capabilities unavailable"}
          className={rowChoiceClass}
        />
      }
    />
  );
}

/** Choosing a model keeps the options it still offers. */
function ModelRow({
  model,
  provider,
  editable,
  onSave,
}: {
  model: RunTitleModel | null;
  provider: AgentProviderCapability | undefined;
  editable: boolean;
  onSave: (next: RunTitleModel) => void;
}) {
  const choose = (id: string) => {
    const next = provider?.models.find((entry) => entry.id === id);
    if (model && next)
      onSave({
        ...model,
        modelId: id,
        modelOptions: buildOptions(next.options, model.modelOptions),
      });
  };
  const models = (provider?.models ?? []).map((entry) => ({
    id: entry.id,
    label: entry.label ?? entry.id,
  }));
  return (
    <SettingsRow
      title="Model"
      control={
        <ChoiceMenu
          id="run-title-model"
          label="Model"
          value={model?.modelId ?? ""}
          choices={withSaved(models, model?.modelId ?? "", "model")}
          onChange={choose}
          disabled={!editable || !provider}
          placeholder={model ? "Choose a model" : "Choose a provider instance first"}
          className={rowChoiceClass}
        />
      }
    />
  );
}

/** One model option the catalog offers for the chosen model, saved with the model. */
function OptionRow({
  descriptor,
  model,
  editable,
  onSave,
}: {
  descriptor: AgentModelOptionDescriptor;
  model: RunTitleModel;
  editable: boolean;
  onSave: (next: RunTitleModel) => void;
}) {
  const value = optionValue(model.modelOptions, descriptor);
  const setValue = (next: AgentModelOptionValue["value"]) =>
    onSave({
      ...model,
      modelOptions: [
        ...model.modelOptions.filter((option) => option.id !== descriptor.id),
        { id: descriptor.id, value: next },
      ],
    });
  return (
    <SettingsRow
      title={descriptor.label}
      control={(text) =>
        descriptor.type === "boolean" ? (
          <Switch
            aria-labelledby={text.title}
            checked={Boolean(value)}
            disabled={!editable}
            onCheckedChange={setValue}
          />
        ) : (
          <ModelOptionSelect
            id={`run-title-option-${descriptor.id}`}
            label={descriptor.label}
            descriptor={descriptor}
            value={value}
            onChange={setValue}
            saving={!editable}
            className={rowChoiceClass}
          />
        )
      }
    />
  );
}

/** The latest eligibility failure; neutral, because a skipped title never affects the Run. */
const DIAGNOSTIC_OUTCOMES: Record<RunTitleDiagnostic["outcome"], string> = {
  skipped: "Skipped",
  failed: "Failed",
  "timed-out": "Timed out",
};

function LatestResult({ diagnostic }: { diagnostic: RunTitleDiagnostic }) {
  const run = diagnostic.runNumber === null ? "A Run" : `Run #${diagnostic.runNumber}`;
  return (
    <SettingsGroup label="Latest result">
      <SettingsRow
        title={
          <span className="flex flex-wrap items-center gap-3">
            <StatusPill tone="neutral">{DIAGNOSTIC_OUTCOMES[diagnostic.outcome]}</StatusPill>
            <span>{`${run} · ${dayAndTime(diagnostic.recordedAt)}`}</span>
          </span>
        }
        description={`${diagnostic.message} The Run kept its automatic title and was otherwise not affected.`}
      />
    </SettingsGroup>
  );
}

/** How generation works, and US 10: what the title model can reach; its prompt is not enforced. */
function HowItWorks() {
  return (
    <SettingsDisclosure
      label="How it works"
      hint="One short-lived T3 thread per Run · fixed built-in prompt · no regenerate"
    >
      <p>
        The Flow starts right away and the generated title arrives a few seconds later. A Run keeps
        its automatic title, the prompt’s first line, when generation does not succeed.
      </p>
      <p>
        Provider instances, models and options come from T3 on the Factory host. Each new Run gets
        one short-lived T3 thread with a fixed built-in prompt; there is no prompt to edit and no
        regenerate action.
      </p>
      <p>
        The title model runs in the Project checkout with the owner’s T3 permissions, like any T3
        launch. Its prompt forbids reading or editing files, running commands and delegating, but
        Factory does not enforce that.
      </p>
    </SettingsDisclosure>
  );
}
