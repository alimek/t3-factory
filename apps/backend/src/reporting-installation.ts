/**
 * How harness configurations launch the stdio bridge. Source installations use the
 * harness PATH's `node`; a desktop build runs its bundled runtime through a stable
 * launcher in the Factory home, so updates and moves rewrite only that launcher.
 */
export type BridgeRuntime =
  | { readonly kind: "path-node" }
  | { readonly kind: "bundled"; readonly executable: string };

const pathNode: BridgeRuntime = { kind: "path-node" };

async function checkRuntime(runtime: BridgeRuntime) {
  if (runtime.kind === "bundled") {
    try {
      await access(runtime.executable, constants.X_OK);
    } catch {
      throw new RepairableInstallationError(
        "The bundled Factory runtime moved or is missing. Repair the installation from this backend.",
      );
    }
    return;
  }
  try {
    await promisify(execFile)("/usr/bin/env", ["node", "--version"], { timeout: 5000 });
  } catch {
    throw Error(
      "Install Node on the harness PATH and recheck Factory MCP. The launcher uses /usr/bin/env node.",
    );
  }
}

const shellQuote = (value: string) => `'${value.replaceAll("'", "'\\''")}'`;
/** Factory-owned launcher text; ELECTRON_RUN_AS_NODE makes the desktop executable a plain Node. */
const launcherSource = (executable: string) =>
  `#!/bin/sh\n# Generated by T3 Factory. Runs the reporting bridge with the desktop application's bundled runtime.\nELECTRON_RUN_AS_NODE=1 exec ${shellQuote(executable)} "$@"\n`;

interface BridgeEntry {
  readonly command: string;
  readonly args: readonly string[];
}

/** Both registrations Factory itself writes; only these may be replaced on repair. */
function bridgeEntries(bridge: string, runtime: BridgeRuntime) {
  const connection = ["--connection-file", join(dirname(bridge), "connection.json")];
  const source: BridgeEntry = { command: "/usr/bin/env", args: ["node", bridge, ...connection] };
  const bundled: BridgeEntry = {
    command: join(dirname(bridge), "factory-runtime-node"),
    args: [bridge, ...connection],
  };
  return runtime.kind === "bundled"
    ? { current: bundled, previous: source }
    : { current: source, previous: bundled };
}

const sameEntry = (saved: Record<string, unknown>, entry: BridgeEntry) =>
  saved.command === entry.command &&
  JSON.stringify(saved.args) === JSON.stringify(entry.args) &&
  Object.keys(saved).every((key) => ["command", "args"].includes(key));

const tomlEntry = (entry: BridgeEntry) =>
  `\n[mcp_servers.factory-runtime]\ncommand = ${JSON.stringify(entry.command)}\nargs = ${JSON.stringify(entry.args)}\n`;

class OtherRuntimeRegistration extends RepairableInstallationError {}

async function refreshLauncher(launcher: string, executable: string) {
  const current = await readConfig(launcher);
  const expected = launcherSource(executable);
  if (current.startsWith("#!/bin/sh\n# Generated by T3 Factory.") && current !== expected)
    await replace(launcher, current, expected, 0o700);
}

async function bridgeMatches(bridge: string, source: URL) {
  try {
    return (await readFile(bridge, "utf8")) === (await readFile(source, "utf8"));
  } catch {
    return false;
  }
}
async function skillMatches(path: string) {
  try {
    return (await readFile(path, "utf8")) === FACTORY_BLOCK_SKILL;
  } catch {
    return false;
  }
}
async function readConfig(path: string) {
  try {
    const info = await lstat(path);
    if (!info.isFile() || info.nlink !== 1)
      throw Error("Symlink, special or hard-linked configuration requires manual setup.");
    return await readFile(path, "utf8");
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code === "ENOENT") return "";
    throw error;
  }
}
async function readReportingConnection(path: string) {
  const contents = await readConfig(path);
  try {
    return JSON.parse(contents);
  } catch (error) {
    if (error instanceof SyntaxError)
      throw new RepairableInstallationError(
        "Factory connection file is missing or invalid. Repair the installation.",
      );
    throw error;
  }
}

async function replace(path: string, before: string, after: string, mode = 0o600) {
  const temp = `${path}.${randomUUID()}.tmp`;
  try {
    const file = await open(temp, "wx", mode);
    try {
      await file.writeFile(after);
      await file.sync();
    } finally {
      await file.close();
    }
    if ((await readConfig(path)) !== before)
      throw Error("Configuration changed during installation. Recheck and retry.");
    await rename(temp, path);
  } finally {
    await unlink(temp).catch(() => undefined);
  }
}
/** Registration text for one provider's configuration; Codex keeps unrelated TOML verbatim. */
function registered(
  target: ReportingInstallation,
  before: string,
  config: Record<string, unknown>,
  entry: BridgeEntry,
  replacing?: BridgeEntry,
) {
  if (target.provider === "codex") {
    // Replace only the exact block Factory appended, keeping comments and formatting.
    if (replacing && !before.includes(tomlEntry(replacing)))
      throw Error(
        "The Factory registration was edited. Review the factory-runtime entry manually.",
      );
    const after = replacing
      ? before.replace(tomlEntry(replacing), tomlEntry(entry))
      : `${before}${tomlEntry(entry)}`;
    parse(after);
    return after;
  }
  const servers = record(config.mcpServers ?? {});
  return (
    JSON.stringify({ ...config, mcpServers: { ...servers, "factory-runtime": entry } }, null, 2) +
    "\n"
  );
}

/**
 * The harness configuration after registering the bridge. A registration Factory wrote for
 * the other runtime is replaced only when `migrate`; anything else is left for manual review.
 */
function configChange(
  target: ReportingInstallation,
  before: string,
  bridge: string,
  runtime: BridgeRuntime,
  migrate = false,
) {
  const { current, previous } = bridgeEntries(bridge, runtime);
  const config = target.provider === "codex" ? parse(before) : record(JSON.parse(before || "{}"));
  const key = target.provider === "codex" ? "mcp_servers" : "mcpServers";
  const existing = record(config[key] ?? {})["factory-runtime"];
  if (existing === undefined) return registered(target, before, config, current);
  const saved = record(existing);
  if (sameEntry(saved, current)) return before;
  if (!sameEntry(saved, previous))
    throw Error(
      "Conflicting factory-runtime entry. Review it manually; Factory will not overwrite another definition or backend's registration.",
    );
  if (!migrate)
    throw new OtherRuntimeRegistration(
      runtime.kind === "bundled"
        ? "Factory reporting is registered for a source installation's Node. Repair to use this desktop application's bundled runtime."
        : "Factory reporting is registered for the desktop application's bundled runtime. Repair to use this source installation's Node.",
    );
  return registered(target, before, config, current, previous);
}

const openReportingInstallation = Effect.fn(function* (
  directory: string,
  stateDirectory: string,
  connection: () => Effect.Effect<Result<T3Connection>, unknown>,
  endpoint: () => string,
  runtime: BridgeRuntime = pathNode,
) {
  const bridge = join(directory, "reporting", "factory-runtime.mjs");
  const canonicalSkill = join(directory, "reporting", "skills", "factory-block", "SKILL.md");
  const launcher = bridgeEntries(bridge, { kind: "bundled", executable: "" }).current.command;
  const source = new URL("./runtime-stdio.mjs", import.meta.url);
  const semaphore = yield* Semaphore.make(1);
  // An application update or move changes only the executable; refresh Factory's own
  // launcher so existing harness registrations keep working without a repair.
  if (runtime.kind === "bundled")
    yield* boundary(() => refreshLauncher(launcher, runtime.executable)).pipe(
      Effect.catchCause(() => Effect.void),
    );
  let closed = false;
  yield* Effect.addFinalizer(() =>
    Effect.gen(function* () {
      closed = true;
      yield* semaphore.withPermits(1)(Effect.void);
    }),
  );
  const targets = Effect.fn(function* () {
    const current = yield* connection();
    if (!current.ok) throw Error("Connection unavailable.");
    return yield* discoverReporting(stateDirectory, current.value);
  });
  const inspect = Effect.fn(function* (
    target: ReportingInstallation,
  ): Generator<Effect.Effect<unknown, unknown>, ReportingInstallation, never> {
    if (!target.path) return target;
    return yield* Effect.gen(function* (): Generator<
      Effect.Effect<unknown, unknown>,
      ReportingInstallation,
      never
    > {
      yield* boundary(() => access(dirname(target.path!), constants.R_OK | constants.W_OK));
      yield* boundary(() => checkRuntime(runtime));
      const before = yield* boundary(() => readConfig(target.path!));
      const after = configChange(target, before, bridge, runtime);
      if (after !== before) return withReportingInstallationActions(target);
      if (
        runtime.kind === "bundled" &&
        (yield* boundary(() => readConfig(launcher))) !== launcherSource(runtime.executable)
      )
        throw new RepairableInstallationError(
          "Factory runtime launcher missing or outdated. Repair the installation from this backend.",
        );
      if (!(yield* boundary(() => bridgeMatches(bridge, source))))
        throw new RepairableInstallationError(
          "Factory bridge missing or outdated. Repair the installation from this backend.",
        );
      if (
        !(yield* boundary(() => skillMatches(factoryBlockSkillPath(target.path!)))) ||
        !(yield* boundary(() => skillMatches(canonicalSkill)))
      )
        throw new RepairableInstallationError(
          "Factory Block skill missing or outdated. Repair the installation from this backend.",
        );
      const saved = yield* boundary(() =>
        readReportingConnection(join(dirname(bridge), "connection.json")),
      );
      if (saved?.endpoint !== endpoint())
        throw new RepairableInstallationError(
          "Owning backend address changed. Repair the installation.",
        );
      return withReportingInstallationActions({
        ...target,
        status: "installed",
        // Native call attribution proves the execution, not its effective configuration.
        // Old evidence.json scopes were inferred from current settings and are not proof.
        runtimeEvidence: "UNVERIFIED",
        message:
          "Configuration installed. Start a fresh session; native approvals, managed restrictions and project overrides still apply.",
      });
    }).pipe(
      Effect.catchCause((cause) => {
        const error = Cause.squash(cause);
        return Effect.succeed(
          withReportingInstallationActions(
            {
              ...target,
              status: "needs-attention" as const,
              message:
                error instanceof Error
                  ? error.message
                  : "Recheck configuration permissions and the Factory bridge.",
            },
            error instanceof RepairableInstallationError,
          ),
        );
      }),
    );
  });
  return {
    getReportingInstallations: Effect.fn(function* (): Generator<
      Effect.Effect<unknown, unknown>,
      Result<readonly ReportingInstallation[]>,
      never
    > {
      return {
        ok: true,
        value: yield* Effect.forEach(yield* targets(), inspect, { concurrency: "unbounded" }),
      };
    }),
    installReporting: (input: unknown) =>
      Effect.suspend(() =>
        closed
          ? Effect.fail(new Error("Reporting installation closed"))
          : semaphore.withPermits(1)(
              Effect.gen(function* (): Generator<
                Effect.Effect<unknown, unknown>,
                Result<ReportingInstallation>,
                never
              > {
                const id = record(input).targetId;
                const target = (yield* targets()).find((target) => target.id === id);
                if (!target?.path)
                  throw Error(
                    "Target unavailable. Recheck the local T3 environment and configuration home.",
                  );
                yield* boundary(() => checkRuntime(runtime));
                const before = yield* boundary(() => readConfig(target.path!));
                const after = configChange(target, before, bridge, runtime, true);
                yield* boundary(() => mkdir(dirname(bridge), { recursive: true, mode: 0o700 }));
                if (runtime.kind === "bundled") {
                  const launcherBefore = yield* boundary(() => readConfig(launcher));
                  yield* boundary(() =>
                    replace(launcher, launcherBefore, launcherSource(runtime.executable), 0o700),
                  );
                }
                const bridgeBefore = yield* boundary(() => readConfig(bridge));
                const bridgeSource = yield* boundary(() => readFile(source, "utf8"));
                yield* boundary(() => replace(bridge, bridgeBefore, bridgeSource));
                const harnessSkill = factoryBlockSkillPath(target.path);
                yield* boundary(() =>
                  mkdir(dirname(harnessSkill), { recursive: true, mode: 0o700 }),
                );
                yield* boundary(() =>
                  mkdir(dirname(canonicalSkill), { recursive: true, mode: 0o700 }),
                );
                const harnessSkillBefore = yield* boundary(() => readConfig(harnessSkill));
                yield* boundary(() =>
                  replace(harnessSkill, harnessSkillBefore, FACTORY_BLOCK_SKILL),
                );
                const canonicalBefore = yield* boundary(() => readConfig(canonicalSkill));
                yield* boundary(() =>
                  replace(canonicalSkill, canonicalBefore, FACTORY_BLOCK_SKILL),
                );
                const connectionFile = join(dirname(bridge), "connection.json");
                const connectionBefore = yield* boundary(() => readConfig(connectionFile));
                yield* boundary(() =>
                  replace(
                    connectionFile,
                    connectionBefore,
                    JSON.stringify({ endpoint: endpoint() }),
                  ),
                );
                if (after !== before) yield* boundary(() => replace(target.path!, before, after));
                const checked = yield* inspect(target);
                if (checked.status !== "installed") throw Error(checked.message);
                return { ok: true, value: checked };
              }).pipe(
                Effect.uninterruptible,
                Effect.catchCause((cause) => {
                  const error = Cause.squash(cause);
                  return Effect.succeed(
                    failure(
                      "validation",
                      error instanceof Error
                        ? error.message
                        : "Installation failed; recheck permissions.",
                    ),
                  );
                }),
              ),
            ),
      ),
  };
});
export class ReportingInstaller extends Context.Service<
  ReportingInstaller,
  Effect.Success<ReturnType<typeof openReportingInstallation>>
>()("ReportingInstaller") {}
export const ReportingInstallerLayer = (...args: Parameters<typeof openReportingInstallation>) =>
  Layer.effect(ReportingInstaller, openReportingInstallation(...args));

const boundary = <A>(operation: () => PromiseLike<A>) =>
  Effect.tryPromise({ try: operation, catch: (error) => error });
